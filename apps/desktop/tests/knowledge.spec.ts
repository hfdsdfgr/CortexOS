import { expect, test } from "@playwright/test";
import { createServer } from "node:http";
import { createWorkspace, launchNative, nativeInvoke } from "./native";
import type { Bootstrap } from "../src/studio";
import type { KnowledgeDetail, KnowledgeNode } from "../src/Knowledge";

test.use({ actionTimeout: 10000 });

test("knowledge drafts preserve source, approval, conflicts and edits across restart", async ({}, testInfo) => {
  test.setTimeout(120_000);
  const server = createServer(async (request, response) => {
    for await (const _chunk of request) { /* drain request */ }
    response.setHeader("Content-Type", "application/json");
    if (request.url === "/api/version") return response.end(JSON.stringify({version:"test-fixture"}));
    if (request.url === "/api/tags") return response.end(JSON.stringify({models:[{name:"qwen3:4b-instruct",size:2500000000}]}));
    if (request.url === "/api/show") return response.end(JSON.stringify({details:{format:"gguf"}}));
    response.end(JSON.stringify({message:{role:"assistant",content:"先验证用户需求，再拆分最小可交付任务。每个版本都应保留验收记录。"},done:true,done_reason:"stop"})+"\n");
  });
  await new Promise<void>((resolve) => server.listen(0,"127.0.0.1",resolve));
  const address=server.address(); if(!address || typeof address === "string") throw new Error("Missing fixture port");
  const endpoint=`http://127.0.0.1:${address.port}`;
  let application=await launchNative(testInfo,{endpoint});
  try {
    let {page}=application;
    await createWorkspace(page,"知识验收 A");
    await expect(page.getByText("Ollama 已连接",{exact:true})).toBeVisible();
    await page.getByRole("textbox",{name:"你的问题",exact:true}).fill("如何推进项目？");
    await page.getByRole("button",{name:"发送消息",exact:true}).click();
    await expect(page.getByText("已完成",{exact:true})).toBeVisible();
    await page.locator(".message.assistant .message-content").evaluate((element) => {
      const range=document.createRange(); range.setStart(element.firstChild!,0); range.setEnd(element.firstChild!,9); const selection=window.getSelection()!;selection.removeAllRanges();selection.addRange(range);
    });
    await page.getByRole("button",{name:"保存为知识",exact:true}).click();
    let editor=page.getByRole("dialog",{name:"新建知识草案",exact:true});
    await expect(editor.getByLabel("正文",{exact:true})).toHaveValue("先验证用户需求，再");
    await editor.getByLabel("标题",{exact:true}).fill("项目推进原则");
    await editor.getByLabel("正文",{exact:true}).fill("先验证用户需求，再拆分任务。");
    await editor.getByRole("button",{name:"保存草案",exact:true}).click();
    await expect(editor).not.toBeVisible();
    await expect(page.getByRole("heading",{name:"知识",exact:true,level:1})).toBeVisible();
    const bootstrap=await nativeInvoke<Bootstrap>(page,"bootstrap");const workspace=bootstrap.workspaces[0].id;
    let list=await nativeInvoke<KnowledgeNode[]>(page,"list_knowledge",{workspaceId:workspace});const id=list[0].id;
    let detail=await nativeInvoke<KnowledgeDetail>(page,"get_knowledge",{workspaceId:workspace,nodeId:id});
    expect(detail.node.effectiveVersion).toBeNull();expect(detail.sourceExcerpt).toBe("先验证用户需求，再");
    await page.getByRole("button",{name:"审核并确认"}).click();
    await page.getByRole("dialog",{name:"确认知识版本"}).getByRole("button",{name:"确认此版本"}).click();
    await expect(page.locator(".knowledge-state")).toContainText("生效版本 v1");
    await page.getByRole("button",{name:"修改草案"}).click();
    editor=page.getByRole("dialog",{name:"修改知识草案",exact:true});
    await editor.getByLabel("正文",{exact:true}).fill("先验证需求，再定义可验证的交付目标。");
    await editor.getByLabel("修改说明",{exact:true}).fill("明确验收目标");
    await nativeInvoke(page,"plugin:window|close",{label:"main"});
    const leaving=page.getByRole("dialog",{name:"保留未保存的修改？"});
    await expect(leaving).toBeVisible();
    await leaving.getByRole("button",{name:"继续编辑"}).click();
    await expect(editor.getByLabel("正文",{exact:true})).toHaveValue("先验证需求，再定义可验证的交付目标。");
    await editor.getByRole("button",{name:"保存草案",exact:true}).click();
    await expect(editor).not.toBeVisible();
    detail=await nativeInvoke<KnowledgeDetail>(page,"get_knowledge",{workspaceId:workspace,nodeId:id});
    expect(detail.node.effectiveVersion).toBe(1);expect(detail.node.latestVersion).toBe(2);
    await page.getByText("对照当前生效版本 v1",{exact:true}).click();
    await expect(page.getByText("先验证用户需求，再拆分任务。",{exact:true})).toBeVisible();
    await page.screenshot({path:testInfo.outputPath("knowledge-draft-comparison.png")});
    await page.getByRole("button",{name:"修改草案"}).click();
    await editor.getByLabel("正文",{exact:true}).fill("我的并发编辑保留");
    await editor.getByLabel("修改说明",{exact:true}).fill("冲突处理");
    await nativeInvoke(page,"save_knowledge",{input:{workspaceId:workspace,nodeId:id,expectedRevision:detail.node.revision,title:"项目推进原则",kind:"knowledge",content:"另一处已保存的修改",changeReason:"并发修改",sourceMessageId:null,sourceExcerpt:null}});
    await editor.getByRole("button",{name:"保存草案",exact:true}).click();
    await expect(editor.getByRole("alert")).toContainText("另一处修改");
    await expect(editor.getByLabel("正文",{exact:true})).toHaveValue("我的并发编辑保留");
    await editor.getByRole("button",{name:"查看最新版本"}).click();
    await expect(editor.getByText("另一处已保存的修改",{exact:true})).toBeVisible();
    await editor.getByRole("button",{name:"已比较，保留我的编辑并重新保存"}).click();
    await editor.getByRole("button",{name:"保存草案",exact:true}).click();
    await expect(editor).not.toBeVisible();
    await page.getByRole("button",{name:"审核并确认"}).click();
    await page.getByRole("button",{name:"确认此版本",exact:true}).click();
    await expect(page.locator(".knowledge-state")).toContainText("生效版本 v4");
    if (!(await page.locator(".version-history").evaluate(el => (el as HTMLDetailsElement).open))) await page.getByText("版本历史（4）",{exact:true}).click();
    await page.getByLabel("查看版本",{exact:true}).selectOption("1");
    await expect(page.locator(".knowledge-detail > .knowledge-prose")).toHaveText("先验证用户需求，再拆分任务。");
    await page.getByLabel("查看版本",{exact:true}).selectOption("4");
    await page.getByText("回答来源",{exact:true}).click();
    await expect(page.locator("blockquote")).toHaveText("先验证用户需求，再");
    await page.getByRole("button",{name:"打开原会话",exact:true}).click();
    await expect(page.locator(".message.assistant .message-content")).toContainText("每个版本都应保留验收记录");
    await createWorkspace(page,"知识验收 B");
    await page.getByRole("navigation").getByRole("link",{name:"知识",exact:true}).click();
    await expect(page.getByRole("heading",{name:"还没有知识",exact:true})).toBeVisible();
    await page.getByLabel("当前工作区").selectOption(workspace);
    await expect(page.locator(".knowledge-row")).toContainText("项目推进原则");
    await page.getByLabel("搜索知识标题").fill("不存在");
    await expect(page.getByRole("heading",{name:"没有匹配的知识"})).toBeVisible();
    await page.getByRole("button",{name:"清除筛选"}).click();
    await page.getByRole("button",{name:"新建知识",exact:true}).click();
    editor=page.getByRole("dialog",{name:"新建知识草案",exact:true});
    await editor.getByLabel("标题",{exact:true}).fill("不应保存");
    await page.keyboard.press("Escape");
    await expect(leaving).toBeVisible();
    await leaving.getByRole("button",{name:"放弃修改"}).click();
    await expect(editor).not.toBeVisible();
    expect((await nativeInvoke<KnowledgeNode[]>(page,"list_knowledge",{workspaceId:workspace})).length).toBe(1);
    expect(application.consoleErrors).toEqual([]);
    await application.closeWindow();await application.stop();
    application=await launchNative(testInfo,{endpoint});page=application.page;
    await page.getByRole("navigation").getByRole("link",{name:"知识",exact:true}).click();
    await page.locator(".knowledge-row").filter({hasText:"项目推进原则"}).click();
    await expect(page.locator(".knowledge-detail > .knowledge-prose")).toHaveText("我的并发编辑保留");
    await expect(page.locator(".knowledge-state")).toContainText("生效版本 v4");
    detail=await nativeInvoke<KnowledgeDetail>(page,"get_knowledge",{workspaceId:workspace,nodeId:id});
    expect(detail.versions.length).toBe(4);expect(detail.sourceExcerpt).toBe("先验证用户需求，再");
    await page.screenshot({path:testInfo.outputPath("knowledge-confirmed.png")});
    await expect(page.locator(".knowledge-history-pane .version-entry")).toHaveCount(4);
    await page.locator(".version-entry").filter({hasText:"从回答保存草案"}).click();
    await expect(page.locator(".knowledge-detail > .knowledge-prose")).toHaveText("先验证用户需求，再拆分任务。");
    await page.getByLabel("查看版本",{exact:true}).selectOption("4");
    for (const width of [1366, 1920]) {
      await page.setViewportSize({width,height:width === 1366 ? 768 : 1080});
      await expect(page.locator(".knowledge-history-pane")).toBeVisible();
      await expect(page.locator('.reference-navigation a[aria-current="page"]')).toHaveText("知识");
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
      await page.locator(".knowledge-history-pane").evaluate(el => { el.scrollTop = 0; });
      await page.screenshot({path:testInfo.outputPath(`knowledge-reference-${width}.png`)});
    }

    await page.setViewportSize({width:375,height:812});
    await expect(page.locator(".knowledge-detail > .knowledge-prose")).toBeVisible();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.screenshot({path:testInfo.outputPath("knowledge-narrow.png")});
    await page.getByLabel("查看版本",{exact:true}).selectOption("1");
    await expect(page.locator(".knowledge-detail > .knowledge-prose")).toHaveText("先验证用户需求，再拆分任务。");
    await page.getByLabel("查看版本",{exact:true}).selectOption("4");
    await page.getByRole("button",{name:"修改草案"}).click();
    await expect(page.getByRole("dialog",{name:"修改知识草案"}).getByLabel("正文",{exact:true})).toBeVisible();
    await page.screenshot({path:testInfo.outputPath("knowledge-editor-narrow.png")});
    await page.getByRole("button",{name:"关闭知识编辑"}).click();
    await expect(page.getByRole("dialog",{name:"修改知识草案"})).not.toBeVisible();
    await page.setViewportSize({width:1440,height:900});
    await page.getByRole("button",{name:"新建知识",exact:true}).click();
    editor=page.getByRole("dialog",{name:"新建知识草案",exact:true});
    await editor.getByLabel("标题",{exact:true}).fill("关闭前保存的手动记录");
    await editor.getByLabel("正文",{exact:true}).fill("正常关闭仍保留草案。");
    await nativeInvoke(page,"plugin:window|close",{label:"main"});
    await page.getByRole("dialog",{name:"保留未保存的修改？"}).getByRole("button",{name:"保存草案",exact:true}).click();
    await expect.poll(() => page.isClosed()).toBe(true);
    await application.stop();
    application=await launchNative(testInfo,{endpoint});page=application.page;
    list=await nativeInvoke<KnowledgeNode[]>(page,"list_knowledge",{workspaceId:workspace});
    expect(list.some((item) => item.title === "关闭前保存的手动记录" && item.effectiveVersion === null)).toBe(true);
    expect(application.consoleErrors).toEqual([]);
  } finally { await application.stop(); await new Promise<void>((resolve) => server.close(() => resolve())); }
});
